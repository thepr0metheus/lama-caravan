// Reads the table in the language the app is set to. The language is read on
// every call rather than once: a test switches it between pins, and nothing
// here may cache a word in the wrong language.
export class HfText {
  constructor(storage) {
    this.storage = storage;
  }

  get lang() {
    try {
      const code = this.storage && this.storage.getItem(LANG_KEY);
      return code && HFS[code] ? code : "en";
    } catch {
      return "en";
    }
  }

  // A key missing from a language falls back to English, then to the key
  // itself — the guard keeps both from happening in a shipped build.
  t(key, vars = {}) {
    const own = HFS[this.lang];
    let text = Object.prototype.hasOwnProperty.call(own, key) ? own[key]
      : (Object.prototype.hasOwnProperty.call(HFS.en, key) ? HFS.en[key] : key);
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
    return text;
  }

  // "3mo ago" and friends. A date in the future (clocks disagree) is "today",
  // not "-2d ago".
  ago(iso, now = Date.now()) {
    if (!iso) return "";
    const at = new Date(iso).getTime();
    if (Number.isNaN(at)) return "";
    const days = Math.floor((now - at) / 86400000);
    if (days <= 0) return this.t("agoToday");
    if (days === 1) return this.t("agoYesterday");
    if (days < 30) return this.t("agoDays", { n: days });
    if (days < 365) return this.t("agoMonths", { n: Math.floor(days / 30) });
    return this.t("agoYears", { n: Math.floor(days / 365) });
  }

  tour() {
    return HF_TOUR[this.lang] || HF_TOUR.en;
  }
}

// Numbers the page prints, one rule each. Sizes are binary gigabytes, the unit
// the models disk and the rest of the app speak.
export class HfFormat {
  static count(n) {
    const v = Number(n) || 0;
    if (v >= 1e6) return `${(v / 1e6).toFixed(1)}M`;
    if (v >= 1e3) return `${(v / 1e3).toFixed(1)}k`;
    return String(v);
  }

  static bytes(b) {
    const v = Number(b) || 0;
    if (!v) return "—";
    if (v >= 1073741824) return `${(v / 1073741824).toFixed(1)} GB`;
    return `${Math.max(1, Math.round(v / 1048576))} MB`;
  }

  static gib(b, digits = 1) {
    return ((Number(b) || 0) / 1073741824).toFixed(digits);
  }

  // A time left in the page's words: the rule is the board's (pace-rule.js, which /models words through the shared
  // dictionary), the three phrases are this table's copies of the shared ones (check_i18n_calls.py keeps them equal).
  static eta(seconds) {
    return PaceRule.eta(seconds, hfT);
  }
}

export const hfText = new HfText(globalThis.localStorage);
export const hfT = (key, vars) => hfText.t(key, vars);
